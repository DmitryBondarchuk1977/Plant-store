-- ============================================================
--  012: фиксация цены закупки в позиции заявки (честная маржа)
--  Себестоимость запоминается на момент заказа/добавления позиции,
--  чтобы маржа в аналитике не «плыла» при изменении текущей цены закупки.
--  Безопасно к повторному запуску.
-- ============================================================

alter table public.request_items
  add column if not exists cost_price numeric(12,2);   -- цена закупки на момент заказа, Br

-- Разовое заполнение для уже существующих заявок: берём текущую цену закупки товара
-- (для истории это лучшее доступное приближение). Новые заявки пишут снапшот сами.
update public.request_items ri
   set cost_price = p.cost_price
  from public.products p
 where ri.product_id = p.id
   and ri.cost_price is null
   and p.cost_price is not null;
